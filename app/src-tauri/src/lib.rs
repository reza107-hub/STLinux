mod accounts;
mod git;

pub fn run() {
  tauri::Builder::default()
    .plugin(tauri_plugin_dialog::init())
    .plugin(tauri_plugin_opener::init())
    .invoke_handler(tauri::generate_handler![
      accounts::startup,
      accounts::add_account,
      accounts::remove_account,
      accounts::list_remote_repos,
      accounts::ssh_generate,
      accounts::ssh_test,
      accounts::ssh_forget,
      accounts::ssh_restore_hidden,
      accounts::ssh_delete,
      accounts::check_account,
      git::git_version,
      git::open_repo,
      git::init_repo,
      git::clone_repo,
      git::repo_summary,
      git::status,
      git::refs,
      git::log,
      git::commit_details,
      git::commit_files,
      git::commit_diff,
      git::working_diff,
      git::recent_messages,
      git::stage,
      git::unstage,
      git::discard,
      git::apply_patch,
      git::commit,
      git::fetch,
      git::pull,
      git::push,
      git::checkout,
      git::create_branch,
      git::delete_branch,
      git::merge,
      git::abort_operation,
      git::rebase,
      git::cherry_pick,
      git::revert_commit,
      git::reset,
      git::tag_create,
      git::tag_delete,
      git::remote_add,
      git::remote_remove,
      git::stash_save,
      git::stash_action,
      git::flow_config,
      git::flow_init,
      git::flow_start,
      git::flow_finish,
      git::read_conflict_file,
      git::resolve_conflict,
      git::ignore_add,
      git::get_identity,
      git::set_identity,
      git::open_terminal,
      git::open_in_files,
    ])
    .run(tauri::generate_context!())
    .expect("error while running STLinux");
}
